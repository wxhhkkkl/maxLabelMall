/**
 * 占位内容种子数据 —— 供无设计稿的信息页与设计稿自带的未确认声明使用
 * ============================================================================
 *
 * ⚠️ 本文件是所有**业务文案的唯一来源**。视图 MUST NOT 内联任何业务文案字符串。
 *
 * 为什么这样做：
 *   - 这些内容涉及**真实业务事实**（公司简介与数据、联系方式、招聘岗位、新闻、
 *     版本日志、模板数量、协议条款、备案号），由实现者编造等于在正式站点上发布
 *     虚假信息；
 *   - 用 `[[ ]]` 包裹后，布局能正常渲染（字符串长度已按真实文案量级给足，方便你
 *     直接看着调版式）。⚠️ 方括号**只存在于本文件里** —— 页面上由 `PendingText`
 *     经 `displayText()` 去掉包裹后才显示，页面上看不见方括号。"这句还没确认"这一事实
 *     改由 `data-content-pending` 属性承载：门禁① 扫本文件、门禁② 扫 DOM 属性，
 *     两条都不受影响。
 *
 * ── 替换流程（只需改这一个文件） ─────────────────────────────────────────────
 *   视图统一用 `<PendingText :value="seed.xxx.yyy" />` 渲染业务文案，该组件**从值
 *   本身派生** `data-content-pending`（见 `isPending`），不需要逐处手写属性。
 *   因此替换时**只改本文件的字符串**：把 `p('…')` 改成 `'…'`（去掉 `[[ ]]` 包裹）
 *   即可，视图一行都不用动。
 *
 *   ⚠️ 早期版本的说明要求"改文件 + 逐个删掉视图里的属性"，那与"只改一个文件"自相
 *   矛盾，且 `isPending` 当时没有导出、视图无法派生属性。现已修正为上面的方案。
 *
 * ── 上线门禁（三条，定义见 quickstart.md §4.6） ──────────────────────────────
 *   ① 权威（CI 可跑）: `pnpm test` 中 `placeholders.spec.ts` 断言 `hasPendingContent() === false`
 *   ② 渲染层（人工）: `document.querySelectorAll('[data-content-pending]').length === 0`
 *   ③ 覆盖性（可 grep）: `storefront/src/views/` 中**不得出现**任何业务文案字面量
 *      —— 即 `grep -rn "50,000+\|顺丰供应链\|首单立减\|满 499" src/views/` 为空。
 *      这条专治"视图绕过占位符直接写死文案"（门禁 ①② 都发现不了这种情况）。
 *
 *   ⚠️ 早期版本的门禁③ 写作 `grep -c "p(" … 归零`，**按构造不可能通过**：本文件的
 *   注释里就含字面 `p(`，且 `grep -c` 数的是行不是调用数、`p(` 还会匹配 `.map(`。
 *   该条已删除。同理，早期把 `legal.privacyChecklist`（永不渲染）放在扫描范围内，
 *   会让门禁 ① 永久为真；现已移出 `RENDERED`。
 */

/** 占位标记：由 `PendingText` 组件从值派生，不需要手写 */
export const PENDING_ATTR = 'data-content-pending';

/** 占位文本的统一前后缀 */
const L = '[[';
const R = ']]';
/** 包一层占位标记 */
const p = (s: string) => `${L}${s}${R}`;

/**
 * 判定一个字符串是否仍是占位文案。
 * **视图 MUST 用它派生 `data-content-pending`**，不得手写该属性 —— 手写会让
 * "替换只需改一个文件"这一承诺失效（早期版本正是这个缺陷）。
 */
export function isPending(v: unknown): boolean {
  return typeof v === 'string' && v.startsWith(L) && v.endsWith(R);
}

/**
 * 渲染用文本 —— 占位文案**去掉首尾那对方括号**，其余原样返回。
 *
 * 方括号是种子文件里的标识，不该出现在页面上。去掉显示后，"未确认"由
 * `PendingText` 的 `data-content-pending` 属性承载（门禁② 仍能扫到）。
 * ⚠️ 只剥首尾各一层，值内部的方括号（如「型号 [A3] 待确认」）必须原样保留。
 */
export function displayText(v: string): string {
  return isPending(v) ? v.slice(L.length, -R.length) : v;
}

/** 供 `placeholders.spec.ts` 断言：RENDERED 中任何一处仍带占位标记即返回 true */
export function hasPendingContent(): boolean {
  return JSON.stringify(RENDERED).includes(L);
}


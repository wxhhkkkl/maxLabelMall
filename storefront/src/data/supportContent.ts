export function findSupportArticle(slug: string) { return supportArticles.find((article) => article.slug === slug) }
export function searchSupportArticles(query: string, category = 'all') {
  const words = query.toLocaleLowerCase().trim().split(/\s+/).filter(Boolean)
  return supportArticles.filter((article) => (category === 'all' || article.category === category)
    && words.every((word) => [article.title, article.summary, ...article.keywords, ...article.sections.map((section) => section.text)].join(' ').toLocaleLowerCase().includes(word)))
}

/**
 * 横幅（`AppBannerRespVO`）。运营在后台「营销中心 → 内容管理 → Banner」维护。
 *
 * ⚠️ 响应里**没有** `status`：后端那个接口只按 `position` 等值查询，**停用的也会返回**。
 * 所以前端无法、也不该做"停用即不展示"的判断（见 `contracts/app-api.md` §5.1）。
 */
export interface Banner {
  id: number
  /**
   * 标题 —— **主文案**，按换行分多行渲染。
   * 同时也当图片的 `alt`。
   */
  title: string
  /** 跳转地址。**可为空** —— 为空时点击不得跳转、也不得报错（FR-083） */
  url?: string
  /** 图片地址。**前景是产品图**（文字由前端排版叠在左侧；手机上文字在上、图移到底部） */
  picUrl: string
  /**
   * 后台表单里的「描述」。**按换行拆两用**（2026-10-10 与所有者约定的口径）：
   * 第一行 = 副标题、第二行 = 胶囊（如"软件开发中"）；没有第二行就不渲染胶囊。
   *
   * ⚠️ 这个字段**当前 C 端接口并不返回**（`AppBannerRespVO` 里没有它），
   * 需要后端补一行才能拿到 —— 见 `contracts/app-api.md` §5.1。
   * 前端照常建模，后端补上即自动生效。
   */
  memo?: string
}

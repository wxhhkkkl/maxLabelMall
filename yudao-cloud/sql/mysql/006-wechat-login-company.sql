-- ============================================================================
-- 006 —— 给会员加「公司名称」，供微信扫码登录首次补全资料时采集
--
-- ⚠️ 与 002/003/004 不同：那几份是**建新东西**；005 与这份都是**改官方建表脚本的现状**，
--    所以重建库时也要补跑（`member-2026-05-30.sql` 里那张 `member_user` 没有这一列）。
--
-- 为什么要它（specs/005-wechat-scan-login Q24 / FR-138）
-- ----------------------------------------------------------------------------
--   客户用微信扫码首次登录时，要在一个「补全页」上填手机号（必填）与公司名称、头像（选填）。
--   手机号与头像都有现成字段，**唯独公司名称没有** —— 实测线上 `information_schema` 确认：
--   `member_user` 现有字段里没有任何一个能承载它（`mark` 是会员备注，语义不同）。
--
-- 它是**会员档案的一项**，不是一个一次性的表单答案：
--   采集之后在前台「个人资料」里可看可改，运营在后台也能看到。所以跟着会员走、加在 `member_user` 上；
--   只为这一个字段另建一张扩展表属于"为单字段引入抽象层"。
--
-- 为什么可空、为什么 64
-- ----------------------------------------------------------------------------
--   · **可空**：它是选填项；而且存量会员（线上 93 个）全都没有这一项。
--     加成 NOT NULL 会让既有行直接不合法。
--   · **64**：公司全称一般在 30 字以内，64 留有余量；与 `name`（真实名字，30）区分开。
--
-- 幂等 / 回滚
-- ----------------------------------------------------------------------------
--   幂等：MODIFY 到同一个定义重复执行不改语义，可安全重跑。
--   回滚：`ALTER TABLE member_user DROP COLUMN company;` —— 会**丢掉所有已填的公司名称**，
--         执行前先想清楚。
-- ============================================================================

ALTER TABLE `member_user`
    ADD COLUMN `company` varchar(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci
        NULL DEFAULT NULL COMMENT '公司名称（微信扫码登录补全时采集，选填）'
        AFTER `avatar`;

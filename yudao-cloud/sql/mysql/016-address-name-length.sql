-- ============================================================================
-- 016 —— 放宽 member_address.name：varchar(10) 装不下 11 位的手机号
--
-- 现象（2026-10-22 客户报「新增收货地址 → 系统异常」）
-- ----------------------------------------------------------------------------
--   客户把手机号 `18748935785`（11 个字符）同时填进「收件人」和「详细地址」，
--   点保存只看到橙色的「系统异常」。
--
--   `name` 是 `varchar(10)`，线上 sql_mode 含 STRICT_TRANS_TABLES —— INSERT 直接报
--   `Data too long for column 'name' at row 1`，不会被截断。这是个没人接的
--   DataIntegrityViolationException，走 GlobalExceptionHandler 的兜底分支，
--   客户只能拿到 `{code:500, msg:"系统异常"}`。
--
--   同一个表单上 `detail_address` 是 varchar(250)、`mobile` 是 varchar(20)，
--   都不会炸 —— 只有收件人卡在 10 个字符。
--
-- 为什么是 64
-- ----------------------------------------------------------------------------
--   10 个字符是照"人名"估的，带括号的代收人（「张三（前台）」）、公司名
--   （「XX贸易有限公司收货处」）都会超。64 与 `member_user.nickname` 等常见
--   文本列同量级，也远大于任何真实收件人。
--
-- 配套改动（缺一不可）
-- ----------------------------------------------------------------------------
--   · 前端收件人输入框加 maxlength=64（AddressFormDialog.vue）
--   · `AppAddressBaseVO.name` 加 @Size(max = 64)，超长时返回可读文案而不是 500
--   · `member-2026-05-30.sql` 建表脚本已同步改成 varchar(64)，重建库时不用再补跑
--
-- 幂等 / 回滚
-- ----------------------------------------------------------------------------
--   幂等：MODIFY 到同一个定义重复执行不改语义，可安全重跑。
--   回滚：改回 varchar(10) 即可 —— 但只有表里没有超过 10 字符的值时才可行。
--         执行前的全表最大值是 5 个字符，可以回滚。
-- ============================================================================

-- 线上现为 varchar(10) NOT NULL，无默认值，utf8mb4_bin（与表默认一致，显式照抄）
ALTER TABLE `member_address`
    MODIFY COLUMN `name` varchar(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin
        NOT NULL COMMENT '收件人名称';

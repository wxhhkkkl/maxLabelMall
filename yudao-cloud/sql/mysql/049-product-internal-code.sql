-- 049 商品内部编码（2026-11-18）
--
-- 变更：`product_spu` 增加 `internal_code`（选填）。运营可在商品编辑「基础设置」里填写，
--       后台商品详情与 **C 端商品详情页的「规格与库存」标签**都会展示（按「商品编码」呈现）。
--
-- 口径：
--   · 选填；NULL / 空串都表示没填，页面不展示
--   · 纯展示字段，不参与搜索与下单
--   · C 端对客户显示为「商品编码」（不暴露“内部”这一说法）
--
-- 上线顺序：先执行本脚本 → 再发后端 → 最后发管理端 / 门面站。
--
-- 回滚：
--   ALTER TABLE `product_spu` DROP COLUMN `internal_code`;
-- ============================================================================

ALTER TABLE `product_spu`
  ADD COLUMN `internal_code` varchar(64) NULL DEFAULT NULL
    COMMENT '商品内部编码（选填；后台与 C 端商品详情展示）'
    AFTER `name`;
